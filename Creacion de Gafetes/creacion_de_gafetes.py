flag_cache = {}

def get_flag(country_code):
    if not country_code or len(country_code) != 2:
        return None
    cc = country_code.lower()
    if cc in flag_cache:
        return flag_cache[cc]
    try:
        resp = requests.get(f"https://flagcdn.com/w80/{cc}.png", timeout=5)
        if resp.status_code == 200:
            flag_cache[cc] = ImageReader(BytesIO(resp.content))
            return flag_cache[cc]
    except:
        pass
    flag_cache[cc] = None
    return None

