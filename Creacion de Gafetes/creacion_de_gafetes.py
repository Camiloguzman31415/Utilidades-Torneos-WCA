def format_cs(cs):
    if pd.isna(cs) or cs == "" or cs == 0:
        return ""
    cs = int(cs)

    sec = cs // 100
    cs_rem = cs % 100
    mins = sec // 60
    sec = sec % 60

    if mins > 0:
        return f"{mins}:{sec:02d}.{cs_rem:02d}"
    else:
        return f"{sec}.{cs_rem:02d}"


def format_mbf(val):
    """Formatea el tiempo de 3x3 Multi-Blind"""
    if pd.isna(val) or val == "" or val == 0:
        return ""
    val = int(val)
    val_str = str(val)
    
    # El formato WCA para 333mbf:
    # El formato "new" es: 0DDTTTTTMM (10 dígitos)
    # difference = 99 - DD
    # timeInSeconds = TTTTT (5 dígitos)
    # missed = MM
    # solved = difference + missed
    # attempted = solved + missed
    
    # Pero la API puede devolver valores con diferente longitud
    # Ajustar según la longitud
    if len(val_str) == 9:
        # Formato sin el 0 inicial
        DD = int(val_str[:2])
        TTTTT = int(val_str[2:7])
        MM = int(val_str[7:])
    elif len(val_str) == 10:
        DD = int(val_str[1:3])
        TTTTT = int(val_str[3:8])
        MM = int(val_str[8:])
    else:
        #other lengths - try to handle generically
        DD = int(val_str[:2])
        MM = int(val_str[-2:])
        TTTTT = int(val_str[2:-2])
    
    difference = 99 - DD
    missed = MM
    solved = difference + missed
    attempted = solved + missed
    time_seconds = TTTTT
    
    if time_seconds == 99999:
        if solved > 0:
            return f"{solved}/{attempted}"
        else:
            return ""
    
    mins = time_seconds // 60
    secs = time_seconds % 60
    
    if mins > 0:
        time_str = f"{mins}:{secs:02d}"
    else:
        time_str = f"{secs}"
    
    if solved > 0:
        return f"{solved}/{attempted} {time_str}"
    else:
        return ""
    val = int(val)
    val_str = str(val)
    
    # El formato de WCA puede ser "old" (9 dígitos) o "new" (10 dígitos)
    # Primero intentamos con formato "old": 1SSAATTTTT
    # solved = 99 - SS
    # attempted = AA
    # timeInSeconds = TTTTT
    
    if len(val_str) == 9:
        # Formato old sin el 1 inicial o con otro dígito
        # Intentamos parsear directamente
        # Estructura: SSAATTTTT (9 dígitos)
        if len(val_str) >= 9:
            try:
                # Para valores como 970075800:
                # Podría ser: SS=97, AA=00, TTTTT=75800
                SS = int(val_str[0:2])
                AA = int(val_str[2:4])
                TTTTT = int(val_str[4:9])
                
                solved = 99 - SS
                attempted = AA
                time_seconds = TTTTT
                
                # Verificar si los valores son razonables
                # attempted debe ser <= 99 y solved <= attempted
                if attempted > 0 and attempted <= 99 and solved <= attempted:
                    if time_seconds <= 99999:
                        mins = time_seconds // 60
                        secs = time_seconds % 60
                        
                        if mins > 0:
                            time_str = f"{mins}:{secs:02d}"
                        else:
                            time_str = f"{secs}"
                        
                        if solved > 0:
                            return f"{solved}/{attempted} {time_str}"
            except:
                pass
    
    # Si el formato old no funcionó, intentamos con formato new: 0DDTTTTTMM
    val_str = val_str.zfill(10)
    
    DD = int(val_str[:2])
    TTTTT = int(val_str[2:7])
    MM = int(val_str[7:])
    
    difference = 99 - DD
    missed = MM
    solved = difference + missed
    attempted = solved + missed
    time_seconds = TTTTT
    
    if time_seconds == 99999:
        if solved > 0:
            return f"{solved}/{attempted}"
        else:
            return ""
    
    time_seconds = TTTTT
    mins = time_seconds // 60
    secs = time_seconds % 60
    
    if mins > 0:
        time_str = f"{mins}:{secs:02d}"
    else:
        time_str = f"{secs}"
    
    if solved > 0:
        return f"{solved}/{attempted} {time_str}"
    else:
        return ""


# 🔴 NORMALIZACIÓN REAL DE FEWEST MOVES
def normalize_fm(val):
    if pd.isna(val) or val == "" or val == 0:
        return None

    val = float(val)

    # Caso 0.27 → 27
    if val < 1:
        return val * 100

    # Caso 2700 → 27
    if val >= 100:
        return val / 100

    # Caso 27 → 27
    return val


def format_fm(val, is_average=False):
    moves = normalize_fm(val)
    if moves is None:
        return ""

    if is_average:
        return f"{moves:.2f}".rstrip("0").rstrip(".")
    else:
        return str(int(round(moves)))


def format_by_event(row, field):
    if row["event"] == "333fm":
        return format_fm(row[field], is_average=(field == "average"))
    elif row["event"] == "333mbf":
        return format_mbf(row[field])
    else:
        return format_cs(row[field])


